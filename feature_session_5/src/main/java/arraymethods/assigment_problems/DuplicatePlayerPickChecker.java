package arraymethods.assigment_problems;

/**
 * Problem 2 (Easy) — Duplicate Player Pick Checker.
 * Reports the first duplicate player name using plain nested loops.
 *
 * Expected Output (running this file's main method):
 *
 * Duplicate Found: Kohli
 * No Duplicates Found
 */
public class DuplicatePlayerPickChecker {

    static String findDuplicatePick(String[] playerNames) {
        for (int i = 0; i < playerNames.length; i++) {
            for (int j = i + 1; j < playerNames.length; j++) {
                if (playerNames[i].equals(playerNames[j])) {
                    return "Duplicate Found: " + playerNames[i];
                }
            }
        }
        return "No Duplicates Found";
    }

    public static void main(String[] args) {
        System.out.println(findDuplicatePick(new String[]{"Kohli", "Bumrah", "Kohli", "Rohit"}));
        System.out.println(findDuplicatePick(new String[]{"Kohli", "Bumrah", "Rohit"}));
    }
}
